import { Injectable } from '@nestjs/common';
import { randomBytes } from 'crypto';
import { mkdir, readFile, writeFile, rename, unlink, chmod } from 'fs/promises';
import { dirname, join } from 'path';
import { addToGitExclude } from '../../../common/git-exclude';
import { parseJsonc, setJsoncValue } from '../../../common/jsonc';
import { createLogger } from '../../../common/logging/logger';
import { ProcessExecutor } from '../../terminal/services/process-executor/process-executor.port';
import { HooksConfigService } from './hooks-config.service';
import type { HookConfigInstaller } from './copilot-hooks-config.service';

const logger = createLogger('DevinHooksConfigService');

const CONFIG_FILE_MODE = 0o600;
const SCRIPT_FILE_MODE = 0o755;
/** SessionStart is a lifecycle confirmation, never turn-critical — it can wait. */
const SESSION_START_TIMEOUT_SEC = 10;
/** Devin's wait cap for the UserPromptSubmit and Stop relay entries, in seconds. */
const TURN_HOOK_TIMEOUT_SEC = 2;
const RELAY_MARKER = 'devchain-relay.sh';
/** Project-relative files that this installer writes. */
const DEVIN_CONFIG_FILE = '.devin/config.local.json';
const DEVIN_RELAY_FILE = `.devin/hooks/${RELAY_MARKER}`;

/**
 * Project-relative files that DevChain writes under `.devin/` and adds to the
 * git exclude file. Devin excludes its MCP file only when `devin mcp add`
 * writes it, and DevChain writes that file itself.
 */
const DEVCHAIN_DEVIN_FILES = [
  DEVIN_CONFIG_FILE,
  DEVIN_RELAY_FILE,
  '.devin/mcp_config.local.json',
] as const;

/**
 * DevChain Devin relay, materialized to `<project>/.devin/hooks/devchain-relay.sh`.
 *
 * Devin's hook payloads are Claude-compatible JSON on stdin: `hook_event_name`
 * names the event (`SessionStart` | `UserPromptSubmit` | `Stop`), `session_id`
 * is the provider session id (a NAME like `functional-share`, not a UUID), and
 * SessionStart carries `source` (`startup` | `resume`). There is no
 * `transcript_path` — the transcript is bound by `--export` at launch.
 *
 * The config is PROJECT-LEVEL (`<project>/.devin/config.local.json`), so the
 * blast radius is narrower than Copilot's user-level config — but a non-
 * devchain Devin launch inside the project still runs it, so the DEVCHAIN_*
 * blast-radius guard stays first. Fail-open everywhere: Devin is never blocked
 * by a relay error, and hook stdout stays empty (Devin interprets stdout JSON).
 */
const RELAY_SCRIPT_CONTENT = `#!/bin/bash
# DevChain Devin relay — bridges Devin CLI lifecycle hooks to DevChain.
# Auto-generated by DevChain. Do not edit manually.
# Requires: jq, curl

set -euo pipefail

# ── Blast-radius guard ───────────────────────────────────────────────────────
# This config is project-level, so any devin run inside the project executes
# it. Exit instantly (no read, no POST) unless this is a devchain-launched session.
if [ -z "\${DEVCHAIN_API_URL:-}" ]; then exit 0; fi
if [ -z "\${DEVCHAIN_SESSION_ID:-}" ]; then exit 0; fi

# ── Tooling guard (fail-open) ────────────────────────────────────────────────
# The relay must NEVER block devin: if jq/curl are missing, no-op (exit 0)
# instead of dying under set -euo pipefail.
command -v jq >/dev/null 2>&1 || exit 0
command -v curl >/dev/null 2>&1 || exit 0

INPUT="$(cat)" || exit 0

# The hook event name arrives inside the Claude-compatible stdin payload.
HOOK_EVENT_NAME="$(echo "$INPUT" | jq -r '.hook_event_name // empty')" || exit 0
case "$HOOK_EVENT_NAME" in
  SessionStart|UserPromptSubmit|Stop) ;;
  *) exit 0 ;;
esac

# tmux session name (prefer the injected value; fall back to a live query).
TMUX_SESSION="\${DEVCHAIN_TMUX_SESSION_NAME:-}"
if [ -z "$TMUX_SESSION" ] && command -v tmux >/dev/null 2>&1; then
  TMUX_SESSION="$(tmux display-message -p '#S' 2>/dev/null || true)"
fi
if [ -z "$TMUX_SESSION" ]; then exit 0; fi

# ── Provider-payload extraction (fail-open) ──────────────────────────────────
# EVERY jq read is guarded with "|| exit 0": malformed hook JSON no-ops silently
# — it must never crash under set -euo pipefail, and must never POST partial data.
SESSION_ID="$(echo "$INPUT" | jq -r '.session_id // empty')" || exit 0

# 'source' belongs ONLY to SessionStart (DTO is .strict()). It is required there,
# so default to "startup" — a lifecycle confirmation must never be dropped on a
# technicality (devin sends startup|resume; this is just a safety net).
SOURCE=""
if [ "$HOOK_EVENT_NAME" = "SessionStart" ]; then
  SOURCE="$(echo "$INPUT" | jq -r '.source // empty')" || exit 0
  if [ -z "$SOURCE" ]; then SOURCE="startup"; fi
fi

# Hook time in epoch ms orders turn hooks that arrive out of order. BSD date has
# no %N — and non-GNU date (e.g. uutils) can emit untruncated nanoseconds for
# %3N, which is still all digits. Accept only exactly 13 decimal digits, then
# perl, then whole seconds (same fallback chain as the Claude relay).
FIRED_AT_MS=0
case "$HOOK_EVENT_NAME" in
  UserPromptSubmit|Stop)
    FIRED_AT_MS="$(date +%s%3N 2>/dev/null || true)"
    [[ "$FIRED_AT_MS" =~ ^[0-9]{13}$ ]] || FIRED_AT_MS="$(perl -MTime::HiRes=time -e 'printf("%d", time() * 1000)' 2>/dev/null || true)"
    [[ "$FIRED_AT_MS" =~ ^[0-9]{13}$ ]] || FIRED_AT_MS="$(( $(date +%s) * 1000 ))"
    ;;
esac

# Normalize devin's payload into DevChain's hook-event shape. providerName=devin
# + providerSessionId (from session_id) select the provider-neutral ingestion
# path; sessionId/projectId/agentId come from the injected DEVCHAIN_* env. Each
# optional key is added conditionally so every .strict() variant stays clean.
PAYLOAD="$(jq -n \\
  --arg hookEventName "$HOOK_EVENT_NAME" \\
  --arg providerName "devin" \\
  --arg providerSessionId "$SESSION_ID" \\
  --arg source "$SOURCE" \\
  --argjson firedAtMs "$FIRED_AT_MS" \\
  --arg tmuxSessionName "$TMUX_SESSION" \\
  --arg projectId "\${DEVCHAIN_PROJECT_ID:-}" \\
  --arg agentId "\${DEVCHAIN_AGENT_ID:-}" \\
  --arg sessionId "\${DEVCHAIN_SESSION_ID:-}" \\
  '{
    hookEventName: \$hookEventName,
    providerName: \$providerName,
    tmuxSessionName: \$tmuxSessionName,
    projectId: \$projectId,
    agentId: (if \$agentId == "" then null else \$agentId end),
    sessionId: (if \$sessionId == "" then null else \$sessionId end)
  }
  + (if \$providerSessionId != "" then {providerSessionId: \$providerSessionId} else {} end)
  + (if \$source != "" then {source: \$source} else {} end)
  + (if (\$hookEventName == "UserPromptSubmit" or \$hookEventName == "Stop")
     then {firedAtMs: \$firedAtMs} else {} end)
  ')" || exit 0

# Turn hooks: fire and forget. The detached POST outlives this script; nothing
# waits for it, so devin never delays a prompt on the relay.
case "$HOOK_EVENT_NAME" in
  UserPromptSubmit|Stop)
    curl -s -o /dev/null -X POST \\
      -H "Content-Type: application/json" \\
      -d "$PAYLOAD" \\
      "\${DEVCHAIN_API_URL}/api/hooks/events" \\
      --max-time 2 </dev/null >/dev/null 2>&1 &
    exit 0
    ;;
esac

# SessionStart: synchronous post with the longer cap. Fail-open, and stdout stays
# EMPTY — devin interprets relay stdout as hook JSON.
curl -s -f -o /dev/null -X POST \\
  -H "Content-Type: application/json" \\
  -d "$PAYLOAD" \\
  "\${DEVCHAIN_API_URL}/api/hooks/events" \\
  --max-time 10 \\
  >/dev/null 2>&1 || exit 0

exit 0
`;

interface DevinHookEntry {
  type: 'command';
  command: string;
  timeout: number;
}

type HookMergeResult = { ok: true; text: string } | { ok: false; reason: string };

/**
 * DevinHooksConfigService — Devin's parallel to the Claude `HooksConfigService`.
 *
 * Writes a Claude-compatible hook config + relay at the PROJECT level:
 *  - `<project>/.devin/hooks/devchain-relay.sh`   (the normalizing bash relay, chmod +x)
 *  - `<project>/.devin/config.local.json`         (JSON with comments; only the relay
 *    entries are edited in place, so user keys, hooks and comments stay)
 *
 * Devin's config schema matches Claude's `settings.local.json` (`command` +
 * `timeout` entries grouped by event name, no matcher) — it reads
 * `.devin/hooks.v1.json`, `.devin/config.json`, `.devin/config.local.json`,
 * AND the project's `.claude` settings. The last one is why the Claude relay
 * gained a `DEVCHAIN_HOOK_PROVIDER` guard: under a DevChain-launched devin
 * session BOTH hook configs run, and only the devin relay may POST. Because old
 * projects carry a guard-less Claude relay, `ensureHooksConfig` also asks the
 * Claude installer to refresh an existing `.claude` relay in place.
 */
@Injectable()
export class DevinHooksConfigService implements HookConfigInstaller {
  /** Stable provider identity used by the launch pipeline to select this installer. */
  readonly providerName = 'devin';

  constructor(
    private readonly claudeHooksConfig: HooksConfigService,
    private readonly executor: ProcessExecutor,
  ) {}

  private hooksDir(projectRootPath: string): string {
    return dirname(this.relayScriptPath(projectRootPath));
  }

  private relayScriptPath(projectRootPath: string): string {
    return join(projectRootPath, DEVIN_RELAY_FILE);
  }

  private configPath(projectRootPath: string): string {
    return join(projectRootPath, DEVIN_CONFIG_FILE);
  }

  /**
   * Ensure the devin relay script and hook config are in place. Called during
   * session launch — errors are logged but never thrown (non-fatal, same
   * contract as the Claude `HooksConfigService.ensureHooksConfig`).
   */
  async ensureHooksConfig(projectRootPath: string): Promise<void> {
    try {
      await this.materializeRelayScript(projectRootPath);
      await this.mergeHooksConfig(projectRootPath);
      // Devin also executes the project's `.claude` hooks: refresh an existing
      // Claude relay so it carries the DEVCHAIN_HOOK_PROVIDER guard (a fresh
      // .claude install is left to the Claude path — never create it here).
      await this.claudeHooksConfig.refreshRelayScriptIfPresent(projectRootPath);
      await this.excludeDevchainFilesFromGit(projectRootPath);
      logger.info('Devin hooks config ensured successfully');
    } catch (error) {
      logger.error({ error }, 'Failed to ensure devin hooks config (non-fatal)');
    }
  }

  /** Materialize the relay script atomically (tmp + rename), chmod +x. */
  private async materializeRelayScript(projectRootPath: string): Promise<void> {
    const scriptPath = this.relayScriptPath(projectRootPath);
    await mkdir(this.hooksDir(projectRootPath), { recursive: true, mode: 0o700 });
    await this.atomicWrite(scriptPath, RELAY_SCRIPT_CONTENT, SCRIPT_FILE_MODE);
    // Ensure executable after rename (some filesystems may not preserve mode).
    await chmod(scriptPath, SCRIPT_FILE_MODE);
    logger.debug({ scriptPath }, 'Devin relay script materialized');
  }

  /**
   * Install the DevChain relay entries into `<project>/.devin/config.local.json`.
   * The file is JSON with comments, so it is edited in place, never
   * re-serialized. A file that cannot be merged without losing user content
   * stays untouched (warning logged); the launch continues without hooks.
   */
  private async mergeHooksConfig(projectRootPath: string): Promise<void> {
    const configPath = this.configPath(projectRootPath);
    const relayScriptPath = this.relayScriptPath(projectRootPath);

    await mkdir(join(projectRootPath, '.devin'), { recursive: true });

    let original: string | null;
    try {
      original = await readFile(configPath, 'utf-8');
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
      original = null;
    }

    // Turn hooks run on every prompt and turn end, so the relay posts in the
    // background and returns at once; devin stops waiting after the short cap.
    const sessionStartHook: DevinHookEntry = {
      type: 'command',
      command: `"${relayScriptPath}"`,
      timeout: SESSION_START_TIMEOUT_SEC,
    };
    const turnHook: DevinHookEntry = { ...sessionStartHook, timeout: TURN_HOOK_TIMEOUT_SEC };

    // Devin's lifecycle hooks only — no PreToolUse/PostToolUse matcher groups.
    const result = mergeDevchainHooks(original ?? '{}\n', {
      SessionStart: sessionStartHook,
      UserPromptSubmit: turnHook,
      Stop: turnHook,
    });
    if (!result.ok) {
      logger.warn(
        { configPath, reason: result.reason },
        `Left ${configPath} unchanged (${result.reason}); DevChain hooks are not installed`,
      );
      return;
    }
    if (result.text === original) return;

    await this.atomicWrite(configPath, result.text, CONFIG_FILE_MODE);
    logger.debug({ configPath }, 'Devin hooks config merged');
  }

  /**
   * In a git repository, add the DevChain-written `.devin` files to the shared
   * exclude file once, so `git add -A` never commits their absolute paths.
   * Non-fatal: a project outside git (or without git) is skipped silently.
   */
  private async excludeDevchainFilesFromGit(projectRootPath: string): Promise<void> {
    try {
      const added = await addToGitExclude(this.executor, projectRootPath, DEVCHAIN_DEVIN_FILES);
      if (added.length > 0) logger.debug({ added }, 'Devin files added to git exclude');
    } catch (error) {
      logger.warn({ error, projectRootPath }, 'Failed to update git exclude for Devin files');
    }
  }

  /** Atomic write: write a uniquely-named temp file then rename into place. */
  private async atomicWrite(filePath: string, content: string, mode: number): Promise<void> {
    const tmpPath = `${filePath}.tmp.${process.pid}.${randomBytes(8).toString('hex')}`;
    try {
      await writeFile(tmpPath, content, { encoding: 'utf-8', mode });
      await rename(tmpPath, filePath);
    } catch (error) {
      try {
        await unlink(tmpPath);
      } catch {
        // Ignore cleanup errors
      }
      throw error;
    }
  }
}

/**
 * Set the DevChain relay entry of each event in the config text. A relay entry
 * that exists is updated key by key, so its group and sibling user hooks stay;
 * an event without one gets a new group appended. Fails when the text is not
 * valid JSON with comments or `hooks` has an unexpected shape.
 */
function mergeDevchainHooks(
  text: string,
  hooksByEvent: Record<string, DevinHookEntry>,
): HookMergeResult {
  let config: unknown;
  try {
    config = parseJsonc(text);
  } catch {
    return { ok: false, reason: 'not valid JSON with comments' };
  }
  if (!isPlainRecord(config)) return { ok: false, reason: 'root is not an object' };
  // Only an absent key starts empty: `"hooks": null` cannot hold the edits.
  const hooks = config.hooks === undefined ? {} : config.hooks;
  if (!isPlainRecord(hooks)) return { ok: false, reason: '"hooks" is not an object' };

  let output = text;
  for (const [eventName, devchainHook] of Object.entries(hooksByEvent)) {
    const groups = hooks[eventName];
    if (groups === undefined) {
      output = setJsoncValue(output, ['hooks', eventName], [{ hooks: [devchainHook] }]);
      continue;
    }
    if (!Array.isArray(groups)) {
      return { ok: false, reason: `"hooks.${eventName}" is not an array` };
    }

    let relayFound = false;
    groups.forEach((group: unknown, groupIndex) => {
      if (!isPlainRecord(group) || !Array.isArray(group.hooks)) return;
      group.hooks.forEach((entry: unknown, entryIndex) => {
        if (!isRelayEntry(entry)) return;
        relayFound = true;
        for (const [key, value] of Object.entries(devchainHook)) {
          if (entry[key] === value) continue;
          const path = ['hooks', eventName, groupIndex, 'hooks', entryIndex, key];
          output = setJsoncValue(output, path, value);
        }
      });
    });
    if (!relayFound) {
      output = setJsoncValue(output, ['hooks', eventName, -1], { hooks: [devchainHook] });
    }
  }
  return { ok: true, text: output };
}

function isRelayEntry(value: unknown): value is Record<string, unknown> {
  return (
    isPlainRecord(value) &&
    typeof value.command === 'string' &&
    value.command.includes(RELAY_MARKER)
  );
}

function isPlainRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}
